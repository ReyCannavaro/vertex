import { WireCategory } from '../types/cad';

export interface SchematicNode {
  id: string;
  title: string;
  subtitle: string;
  badge: string;
  category: Exclude<WireCategory, 'all'>;
  x: number;
  y: number;
  width: number;
  height: number;
  accentColor: string;
  voltage: string;
  location: string;
  notes: string;
  pins: Array<{
    name: string;
    side: 'left' | 'right' | 'top' | 'bottom';
    offset: number;
    color: string;
  }>;
}

export interface SchematicWire {
  id: string;
  fromNode: string;
  fromPin: string;
  toNode: string;
  toPin: string;
  label: string;
  category: Exclude<WireCategory, 'all'>;
  color: string;
  voltage?: string;
  dashed?: boolean;
  midX?: number;
  note?: string;
}


import { WireCategory } from '../types/cad';

export interface SchematicNode {
  id: string;
  title: string;
  subtitle: string;
  badge: string;
  category: Exclude<WireCategory, 'all'>;
  x: number;
  y: number;
  width: number;
  height: number;
  accentColor: string;
  voltage: string;
  location: string;
  notes: string;
  pins: Array<{
    name: string;
    side: 'left' | 'right' | 'top' | 'bottom';
    offset: number; // px from top (for left/right) or left (for top/bottom)
    color: string;
  }>;
}

export interface SchematicWire {
  id: string;
  fromNode: string;
  fromPin: string;
  toNode: string;
  toPin: string;
  label: string;
  category: Exclude<WireCategory, 'all'>;
  color: string;
  voltage?: string;
  dashed?: boolean;
  /** Optional X/Y bend hint for clean orthogonal schematic routing */
  midX?: number;
  note?: string;
}

export interface PinoutEntry {
  gpio: string;
  module: string;
  signal: string;
  voltage: string;
  safetyNote: string;
}

export interface BomItem {
  name: string;
  qty: string;
  spec: string;
  zone: string;
}

